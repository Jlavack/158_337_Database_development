drop table invoice cascade constraints;

drop table customer cascade constraints;


CREATE TABLE CUSTOMER (
CUST_NUM	NUMBER(5) PRIMARY KEY, 
CUST_LNAME	VARCHAR2(20), 
CUST_FNAME	VARCHAR2(20), 
CUST_BALANCE	NUMBER(8,2) check (CUST_BALANCE >= 0.00));


CREATE TABLE INVOICE (
INV_NUM		NUMBER(5) PRIMARY KEY, 
CUST_NUM	NUMBER(5) not null references customer(cust_num), 
INV_DATE	DATE not null, 
INV_AMOUNT	NUMBER(7,2) default 0.00);

